#!/usr/bin/env bash
# Bundled plugin lifecycle. Sourcing only defines functions.
# shellcheck shell=bash

orcan_write_network_overlay() {
    local name="$1"
    local netf
    netf="$(orcan_compose_network_file)"
    mkdir -p "$(dirname "${netf}")"

    {
        printf '# Generated by orcan up --network (do not edit).\n'
        printf 'services:\n'
        printf '  orcan:\n'
        printf '    environment:\n      ORCAN_NETWORK_ENABLED: "1"\n'
        printf '    networks:\n'
        printf '      - default\n'
        printf '      - orcan_ext\n'
        printf 'networks:\n'
        printf '  orcan_ext:\n'
        printf '    name: %s\n' "${name}"
        printf '    external: true\n'
    } >"${netf}"

    printf '%s\n' "${netf}"
}

orcan_plugin_network_prepare() {
    docker network inspect "${network_name}" >/dev/null 2>&1 || {
        orcan_die "docker network '${network_name}' not found (create it first: docker network create ${network_name})"
        return 1
    }
    orcan_write_network_overlay "${network_name}" >/dev/null
}
orcan_plugin_network_verify() {
    local name
    name="$(orcan_container_name)"
    if ! docker network inspect "${network_name}" --format '{{range .Containers}}{{.Name}} {{end}}' 2>/dev/null | grep -qw "${name}"; then
        orcan_run_selected up -d --force-recreate || return
        docker network inspect "${network_name}" --format '{{range .Containers}}{{.Name}} {{end}}' 2>/dev/null | grep -qw "${name}" || {
            orcan_die "container is not attached to network '${network_name}'"
            return 1
        }
    fi
}
