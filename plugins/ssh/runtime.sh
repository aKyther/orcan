#!/usr/bin/env bash
# Bundled plugin lifecycle. Sourcing only defines functions.
# shellcheck shell=bash

orcan_write_git_overlay() {
    local gitf ssh_dir sock
    local have_ssh=0 have_agent=0
    gitf="$(orcan_compose_git_file)"
    mkdir -p "$(dirname "${gitf}")"
    ssh_dir="${HOME}/.ssh"
    sock="${SSH_AUTH_SOCK:-}"

    if [[ -d "${ssh_dir}" ]]; then
        have_ssh=1
    fi
    if [[ -n "${sock}" && -S "${sock}" ]]; then
        have_agent=1
    fi
    if (( !have_ssh && !have_agent )); then
        orcan_die "orcan up --with-ssh needs ${ssh_dir} or a working SSH_AUTH_SOCK"
    fi

    {
        printf '# Generated by orcan up --with-ssh (do not edit).\n'
        printf 'services:\n'
        printf '  orcan:\n'
        printf '    environment:\n      ORCAN_SSH_ENABLED: "1"\n'
        if (( have_agent )); then
            printf '      SSH_AUTH_SOCK: /run/host-ssh-agent.sock\n'
        fi
        printf '    volumes:\n'
        if (( have_ssh )); then
            printf '      - %s:/home/developer/.ssh:ro\n' "${ssh_dir}"
        elif [[ -f "${ssh_dir}/known_hosts" ]]; then
            printf '      - %s:/home/developer/.ssh/known_hosts:ro\n' "${ssh_dir}/known_hosts"
        fi
        if (( have_agent )); then
            printf '      - %s:/run/host-ssh-agent.sock\n' "${sock}"
        fi
    } >"${gitf}"

    printf '%s\n' "${gitf}"
}

orcan_plugin_ssh_prepare() {
    git_overlay="$(orcan_write_git_overlay)" || return
    orcan_warn "SSH plugin exposes host ~/.ssh and the selected agent to the container."
}
orcan_plugin_ssh_verify() {
    if ! orcan_run_selected exec -T orcan test -d /home/developer/.ssh 2>/dev/null &&
        ! orcan_run_selected exec -T orcan test -S /run/host-ssh-agent.sock 2>/dev/null; then
        orcan_run_selected up -d --force-recreate || return
        orcan_run_selected exec -T orcan test -d /home/developer/.ssh 2>/dev/null ||
            orcan_run_selected exec -T orcan test -S /run/host-ssh-agent.sock 2>/dev/null
    fi
}
